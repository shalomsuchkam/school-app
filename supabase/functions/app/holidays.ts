const sets = new Map<string, Set<string>>();
function setFor(country: string) {
  let s = sets.get(country);
  if (!s) {
    s = new Set([...(FIXED[country] ?? []), ...(MOVABLE[country] ?? [])]);
    sets.set(country, s);
  }
  return s;
}

export function isHoliday(country: string, iso: string) {
  const s = setFor(country);
  return s.has(iso) || s.has(iso.slice(5));
}

// Upcoming holidays for the parent's Schedule screen.
export function holidaysBetween(country: string, from: string, to: string) {
  const out: string[] = [];
  const d = new Date(from + "T00:00:00Z");
  const end = new Date(to + "T00:00:00Z");
  while (d <= end) {
    const iso = d.toISOString().slice(0, 10);
    if (isHoliday(country, iso)) out.push(iso);
    d.setUTCDate(d.getUTCDate() + 1);
  }
  return out;
}
